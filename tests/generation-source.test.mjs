import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm, readFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import os from 'node:os';
import { fileURLToPath } from 'node:url';
import { findPython } from '../files.mjs';
import { extractSource } from '../generation-source.mjs';

test('生成读取全部源文档内容，不复用预览截断数据', async t => {
  const directory = await mkdtemp(path.join(os.tmpdir(), 'source-extraction-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  execFileSync(findPython(), [fileURLToPath(new URL('./make_source_fixtures.py', import.meta.url)), directory], { windowsHide: true });
  const extract = name => extractSource(path.join(directory, name), name);
  const xlsx = await extract('完整表格.xlsx');
  assert.equal(xlsx.units.length, 252);
  assert.equal(xlsx.units[250].originalId, 'IO-251');
  assert.ok(xlsx.units[250].text.includes('专家长意见'.repeat(700)));
  assert.equal(xlsx.units[251].originalId, 'EX-001');
  assert.ok(xlsx.units[251].location.includes('补充意见'));
  assert.equal(xlsx.sha256.length, 64);
  const csv = await extract('多行编码.csv');
  assert.equal(csv.units[0].originalId, 'CSV-001');
  assert.ok(csv.units[0].text.includes('包含逗号,以及\n换行中文'));
  const docx = await extract('完整文档.docx');
  assert.ok(docx.units.map(unit => unit.text).join('').includes('前文标记' + '完整正文'.repeat(4000)));
  assert.equal(docx.units.find(unit => unit.originalId === 'DOC-001').text.includes('表格结论标记'), true);
  assert.equal(docx.units.at(-1).text, '末尾正文标记');
  const pdf = await extract('全部页面.pdf');
  assert.equal(pdf.units.length, 25);
  assert.ok(pdf.units.at(-1).text.includes('Source page 25 complete marker'));
  const plain = await extract('长文本.txt');
  assert.equal(plain.units.map(unit => unit.text).join(''), await readFile(path.join(directory, '长文本.txt'), 'utf8'));
  assert.ok(plain.characters > 200000);
  const json = await extract('记录.json');
  assert.equal(json.units[0].originalId, 'JSON-001');
  assert.equal(JSON.parse(json.units[0].text)['专家意见'], '完整 JSON 记录');
  const jsonl = await extract('记录.jsonl');
  assert.equal(jsonl.units.length, 3); assert.equal(jsonl.units[2].originalId, 'LINE-3');
  await assert.rejects(extract('空文件.txt'), /没有可读取/);
  await assert.rejects(extract('超限.txt'), /200 万字符/);
  await assert.rejects(extractSource(path.join(directory, '空文件.txt'), '旧版.doc'), /暂不支持/);
});
